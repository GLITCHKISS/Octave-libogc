"""The DSP microcodes the vendored libasnd uploads, assembled and written as C headers (GameCube build).

    py Engine/Source/Audio/Dolphin/asnd/dsp/make_ucode.py [--check]

Assembles each source here with devkitPro's gcdsptool (gamecube-tools; the assembler libogc's own build uses) and
writes the image, byte for byte, into the header beside asndlib.c:

    dsp_mixer.s        -> ../asnd_dsp_mixer.h        libasnd's mixer as libogc v3.0.4 ships it (stock)
    dsp_mixer_adpcm.s  -> ../asnd_dsp_mixer_adpcm.h  the same mixer with a DSP-ADPCM voice (Config.ini DspAdpcm=1)

The headers are committed, so a normal build needs no DSP assembler. --check assembles and compares with the committed
headers (and, for the stock mixer, with the image embedded in the installed libasnd.a), changing nothing.
"""
import hashlib
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent
UCODES = [('dsp_mixer.s', 'asnd_dsp_mixer.h', 'asnd_dsp_mixer_bin'),
          ('dsp_mixer_adpcm.s', 'asnd_dsp_mixer_adpcm.h', 'asnd_dsp_mixer_adpcm_bin')]


def devkitpro():
    for c in (os.environ.get('DEVKITPRO_WIN'), os.environ.get('DEVKITPRO'), r'C:\devkitPro', r'C:\gekko-toolchain'):
        if not c:
            continue
        if c.startswith('/') and len(c) > 2 and c[2] == '/':
            c = f'{c[1].upper()}:{c[2:]}'
        elif c.startswith('/opt/devkitpro'):
            c = r'C:\devkitPro'
        if (Path(c) / 'tools' / 'bin').exists():
            return Path(c)
    sys.exit('devkitPro not found (set DEVKITPRO)')


def assemble(tool, src):
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'ucode.bin'
        r = subprocess.run([str(tool), '-c', str(src), '-o', str(out)], capture_output=True, text=True)
        if r.returncode != 0 or not out.exists():
            sys.exit(f'gcdsptool failed on {src.name}:\n{r.stdout}{r.stderr}')
        for line in (r.stdout + r.stderr).splitlines():
            if 'error' in line.lower():
                sys.exit(f'gcdsptool: {src.name}: {line}')
        return out.read_bytes()


def header(src, symbol, image):
    rows = []
    for i in range(0, len(image), 16):
        rows.append('    ' + ', '.join('0x%02x' % b for b in image[i:i + 16]) + ',')
    return (f'/* Generated by asnd/dsp/make_ucode.py from dsp/{src} with gcdsptool: don\'t edit (run it again). */\n'
            f'/* {len(image)} bytes, md5 {hashlib.md5(image).hexdigest()} */\n'
            '#pragma once\n'
            '#include <stddef.h>\n'
            '#include <stdint.h>\n'
            f'static const uint8_t {symbol}[] __attribute__((aligned(32))) = {{\n' + '\n'.join(rows) + '\n};\n'
            f'static const size_t {symbol}_size = {len(image)};\n')


def committed_image(path):
    if not path.exists():
        return None
    text = path.read_text()
    body = text[text.index('= {') + 3:text.index('};')]
    return bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body))


def shipped_stock(dkp):
    """The stock image embedded in the installed libasnd.a (section .rodata.asnd_dsp_mixer_bin)."""
    lib = dkp / 'libogc' / 'lib' / 'cube' / 'libasnd.a'
    ar = dkp / 'devkitPPC' / 'bin' / 'powerpc-eabi-ar.exe'
    objcopy = dkp / 'devkitPPC' / 'bin' / 'powerpc-eabi-objcopy.exe'
    if not (lib.exists() and ar.exists() and objcopy.exists()):
        return None
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([str(ar), 'x', str(lib), 'asnd_dsp_mixer_bin.o'], cwd=tmp, check=True)
        subprocess.run([str(objcopy), '-O', 'binary', '-j', '.rodata.asnd_dsp_mixer_bin', 'asnd_dsp_mixer_bin.o',
                        'shipped.bin'], cwd=tmp, check=True)
        return (Path(tmp) / 'shipped.bin').read_bytes()


def main():
    check = '--check' in sys.argv
    dkp = devkitpro()
    tool = dkp / 'tools' / 'bin' / ('gcdsptool.exe' if os.name == 'nt' else 'gcdsptool')
    ok = True
    for src, out, symbol in UCODES:
        if not (HERE / src).exists():
            continue
        image = assemble(tool, HERE / src)
        if src != 'dsp_mixer.s':
            image += bytes(-len(image) % 32)   # (to whole 32-byte DMA blocks: zero words, never run; the stock image
                                               #  stays as libogc ships it)
        line = f'{src}: {len(image)} bytes, md5 {hashlib.md5(image).hexdigest()}'
        if src == 'dsp_mixer.s':
            shipped = shipped_stock(dkp)
            if shipped is not None:
                same = shipped == image
                ok = ok and same
                line += '; libasnd.a\'s: ' + ('IDENTICAL' if same else 'DIFFERENT')
        if check:
            same = committed_image(OUT / out) == image
            ok = ok and same
            line += f'; {out}: ' + ('up to date' if same else 'STALE')
        else:
            (OUT / out).write_bytes(header(src, symbol, image).encode())
            line += f' -> {out}'
        print(line)
    sys.exit(0 if ok else 1)


main()
